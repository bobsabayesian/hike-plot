// Writes src/features/glyphWidths.ts: the advance width of each character in the poster fonts (Inter and Source
// Serif 4, regular), as a fraction of the font size, so labels can be measured before the fonts load in the browser.
// Run: node scripts/glyph-widths.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const fonts = {
  sans: require.resolve('@fontsource/inter/files/inter-latin-400-normal.woff'),
  serif: require.resolve('@fontsource/source-serif-4/files/source-serif-4-latin-400-normal.woff'),
};
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCharCode(c));
for (let c = 160; c <= 255; c++) chars.push(String.fromCharCode(c));
chars.push('’', '‘', '“', '”', '–', '—', '·', '…', '°');

let out = '// Generated by scripts/glyph-widths.mjs from the regular Inter and Source Serif 4 fonts. Do not edit.\n';
out += '/** advance width of each character, as a fraction of the font size */\n';
out += 'export const GLYPH_WIDTHS: Record<\'sans\' | \'serif\', Record<string, number>> = {\n';
for (const [key, file] of Object.entries(fonts)) {
  const b = readFileSync(file);
  const font = opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
  const w = {};
  for (const ch of chars) {
    const g = font.charToGlyph(ch);
    if (g && g.unicode !== undefined) w[ch] = +(g.advanceWidth / font.unitsPerEm).toFixed(3);
  }
  out += `  ${key}: ${JSON.stringify(w)},\n`;
}
out += '};\n';
writeFileSync(new URL('../src/features/glyphWidths.ts', import.meta.url), out);
console.log('wrote', chars.length, 'characters per font');
